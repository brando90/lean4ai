# Function to extract theorems and proofs from a .lean file
def extract_theorems_and_proofs(file_path: str) -> List[List[str]]:
    entire_file = ""
    with open(file_path, 'r', encoding='utf-8') as file:
        for line in file:
          entire_file += line + " "
    pattern = re.compile(r"(theorem |protected theorem )(.*?)(?=(theorem |protected theorem |def |/-|@|section$))", re.DOTALL)

    matches = pattern.findall(entire_file)
    # Each match includes the starting word ("theorem" or "protected theorem"), the content of the theorem,
    # and the starting word of the next match as the lookahead assertion does not consume characters.
    # We combine the starting word with the content for each theorem and exclude the lookahead part.
    theorems_and_proofs = [match[0] + match[1] for match in matches]

    return theorems_and_proofs

# Walk through the Mathlib directory and process each .lean file
all_theorems = []
num_files_scraped = 0
max_files_scraped = 1000

for root, dirs, files in os.walk(mathlib_dir):
    for file in files:
        if file.endswith(".lean"):
            file_path = os.path.join(root, file)
            theorems_and_proofs = extract_theorems_and_proofs(file_path)
            if len(theorems_and_proofs) > 0:
              all_theorems.extend(theorems_and_proofs)
              num_files_scraped += 1
            if num_files_scraped >= max_files_scraped:
              break
    if num_files_scraped >= max_files_scraped:
      break

all_theorems = [" /newline ".join(theorem.split("\n")) for theorem in all_theorems]
